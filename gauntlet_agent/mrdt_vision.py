"""
Daktari AI — Malaria mRDT Strip Vision Adapter & Synthetic Fixture Simulator.

Safety Contract:
- Live multimodal classification requires an explicit NVIDIA NIM API key (`NVIDIA_API_KEY`),
  and only accepts validated status tokens (`POSITIVE`, `NEGATIVE`, `INVALID`).
- When no vision model API key is configured (or if remote inference fails), the offline
  fallback NEVER infers clinical malaria status from arbitrary image bytes or payload length.
  Untagged images deterministically return `SIMULATION_UNVERIFIED` (`confidence = 0.0`).
- Explicit synthetic PNG fixtures generated by `generate_synthetic_mrdt_png()` (`Comment\x00MRDT_*`)
  are evaluated solely for deterministic software testing and marked `is_simulation = True`.
"""

import base64
from dataclasses import dataclass, field
import io
import json
import logging
import struct
import time
from typing import Optional
import urllib.request
import zlib

logger = logging.getLogger("gauntlet.mrdt")


class MRDTResult:
    POSITIVE = "POSITIVE"                        # Both C-line and T-line visible
    NEGATIVE = "NEGATIVE"                        # C-line visible, no T-line
    INVALID = "INVALID"                          # Missing Control line (faulty cassette)
    SIMULATION_UNVERIFIED = "SIMULATION_UNVERIFIED"  # No vision model configured / untagged image


VALID_CLINICAL_STATUSES = {
    MRDTResult.POSITIVE,
    MRDTResult.NEGATIVE,
    MRDTResult.INVALID,
}


@dataclass
class MRDTClassification:
    status: str
    control_line_detected: bool
    test_line_detected: bool
    band_intensity_ratio: float
    confidence: float
    clinical_recommendation: str
    inference_engine: str
    is_simulation: bool = True
    timestamp: float = field(default_factory=time.time)


class MRDTAnalyzer:
    """Evaluates mRDT cassette imagery with fail-closed offline safety."""

    @classmethod
    def _unverified_fallback(cls, reason: str) -> MRDTClassification:
        return MRDTClassification(
            status=MRDTResult.SIMULATION_UNVERIFIED,
            control_line_detected=False,
            test_line_detected=False,
            band_intensity_ratio=0.0,
            confidence=0.0,
            clinical_recommendation=(
                "SIMULATION_UNVERIFIED: Automated mRDT vision is unavailable or unverified "
                f"({reason}). Do NOT prescribe antimalarials from automated output; perform "
                "manual visual strip inspection per WHO guidelines."
            ),
            inference_engine="Offline Fallback (SIMULATION_UNVERIFIED — No Vision Model)",
            is_simulation=True,
        )

    @classmethod
    def analyze_cassette_image(
        cls,
        image_bytes: bytes,
        api_key: Optional[str] = None,
    ) -> MRDTClassification:
        """
        Evaluate an mRDT cassette image.
        - Uses NVIDIA NIM Vision API when `api_key` is provided.
        - Offline fallback ONLY recognizes explicit `Comment\\x00MRDT_*` synthetic PNG fixtures
          and returns `SIMULATION_UNVERIFIED` for all other payloads.
        """
        if not image_bytes:
            return cls._unverified_fallback("empty image payload")

        if api_key:
            try:
                b64_img = base64.b64encode(image_bytes).decode("utf-8")
                url = "https://integrate.api.nvidia.com/v1/chat/completions"
                payload = {
                    "model": "nvidia/llama-3.2-11b-vision-instruct",
                    "messages": [{
                        "role": "user",
                        "content": [
                            {
                                "type": "text",
                                "text": (
                                    "Analyze this malaria mRDT strip. Is the Control line visible? "
                                    "Is the Test line visible? Output JSON: "
                                    "{\"status\": \"POSITIVE\"|\"NEGATIVE\"|\"INVALID\", \"confidence\": float}"
                                ),
                            },
                            {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{b64_img}"}},
                        ],
                    }],
                    "temperature": 0.05,
                }
                req = urllib.request.Request(
                    url,
                    data=json.dumps(payload).encode("utf-8"),
                    headers={"Content-Type": "application/json", "Authorization": f"Bearer {api_key}"},
                    method="POST",
                )
                with urllib.request.urlopen(req, timeout=12.0) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
                    parsed = json.loads(data["choices"][0]["message"]["content"])
                    raw_status = parsed.get("status")
                    if raw_status not in VALID_CLINICAL_STATUSES:
                        return cls._unverified_fallback("unrecognized model status token")
                    recommendation = (
                        "Administer weight-adjusted Artemether-Lumefantrine (ALu) after clinician confirmation."
                        if raw_status == MRDTResult.POSITIVE
                        else (
                            "Invalid cassette (missing Control line). Repeat test with a new strip."
                            if raw_status == MRDTResult.INVALID
                            else "Negative mRDT. Evaluate non-malarial fever causes per WHO IMCI guidelines."
                        )
                    )
                    return MRDTClassification(
                        status=raw_status,
                        control_line_detected=(raw_status != MRDTResult.INVALID),
                        test_line_detected=(raw_status == MRDTResult.POSITIVE),
                        band_intensity_ratio=0.82 if raw_status == MRDTResult.POSITIVE else 0.0,
                        confidence=float(parsed.get("confidence", 0.90)),
                        clinical_recommendation=recommendation,
                        inference_engine="NVIDIA NIM (nvidia/llama-3.2-11b-vision-instruct)",
                        is_simulation=False,
                    )
            except Exception as e:
                logger.warning("[NVIDIA Vision] Vision call failed (%s). Returning unverified/fixture status.", e)

        # Offline mode: ONLY accept explicit synthetic PNG fixtures generated by generate_synthetic_mrdt_png()
        is_png = image_bytes.startswith(b"\x89PNG\r\n\x1a\n")
        if not is_png:
            return cls._unverified_fallback("no vision API key configured")

        if b"Comment\x00MRDT_INV" in image_bytes:
            return MRDTClassification(
                status=MRDTResult.INVALID,
                control_line_detected=False,
                test_line_detected=False,
                band_intensity_ratio=0.0,
                confidence=0.98,
                clinical_recommendation="[SIMULATION FIXTURE] Invalid cassette: Control line missing. Re-test with new strip.",
                inference_engine="Synthetic PNG Fixture Stub (SIMULATION_ONLY — Non-Clinical)",
                is_simulation=True,
            )
        if b"Comment\x00MRDT_POS" in image_bytes:
            return MRDTClassification(
                status=MRDTResult.POSITIVE,
                control_line_detected=True,
                test_line_detected=True,
                band_intensity_ratio=0.74,
                confidence=0.96,
                clinical_recommendation="[SIMULATION FIXTURE] Synthetic positive mRDT fixture matched for pipeline testing.",
                inference_engine="Synthetic PNG Fixture Stub (SIMULATION_ONLY — Non-Clinical)",
                is_simulation=True,
            )
        if b"Comment\x00MRDT_NEG" in image_bytes:
            return MRDTClassification(
                status=MRDTResult.NEGATIVE,
                control_line_detected=True,
                test_line_detected=False,
                band_intensity_ratio=0.05,
                confidence=0.94,
                clinical_recommendation="[SIMULATION FIXTURE] Synthetic negative mRDT fixture matched for pipeline testing.",
                inference_engine="Synthetic PNG Fixture Stub (SIMULATION_ONLY — Non-Clinical)",
                is_simulation=True,
            )

        return cls._unverified_fallback("untagged image without vision model")

    @classmethod
    def generate_synthetic_mrdt_png(cls, status: str = MRDTResult.POSITIVE) -> bytes:
        """
        Generate a synthetic 100x40 PNG fixture tagged with an explicit `Comment\\x00MRDT_*` tEXt chunk
        for deterministic automated testing.
        """
        width, height = 100, 40
        raw_pixels = bytearray()

        c_visible = (status != MRDTResult.INVALID)
        t_visible = (status == MRDTResult.POSITIVE)

        for y in range(height):
            raw_pixels.append(0)  # Filter byte (None)
            for x in range(width):
                if c_visible and 28 <= x <= 32 and 5 <= y <= 35:
                    raw_pixels.extend([220, 40, 100])
                elif t_visible and 68 <= x <= 72 and 5 <= y <= 35:
                    raw_pixels.extend([220, 40, 100])
                else:
                    raw_pixels.extend([245, 245, 245])

        buf = io.BytesIO()
        buf.write(b"\x89PNG\r\n\x1a\n")

        ihdr_data = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
        buf.write(struct.pack(">I", 13))
        buf.write(b"IHDR")
        buf.write(ihdr_data)
        buf.write(struct.pack(">I", zlib.crc32(b"IHDR" + ihdr_data)))

        marker = (
            "MRDT_POS"
            if status == MRDTResult.POSITIVE
            else ("MRDT_INV" if status == MRDTResult.INVALID else "MRDT_NEG")
        )
        text_data = b"Comment\x00" + marker.encode("ascii")
        buf.write(struct.pack(">I", len(text_data)))
        buf.write(b"tEXt")
        buf.write(text_data)
        buf.write(struct.pack(">I", zlib.crc32(b"tEXt" + text_data)))

        compressed = zlib.compress(bytes(raw_pixels))
        buf.write(struct.pack(">I", len(compressed)))
        buf.write(b"IDAT")
        buf.write(compressed)
        buf.write(struct.pack(">I", zlib.crc32(b"IDAT" + compressed)))

        buf.write(struct.pack(">I", 0))
        buf.write(b"IEND")
        buf.write(struct.pack(">I", zlib.crc32(b"IEND")))

        return buf.getvalue()
